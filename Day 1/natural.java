public class natural {
    static void nat() {
        for (int i = 1; i <= 100; i++) {
            System.out.println("Natural numbers =" + i);
        }
    }

    static void whole() {
        for (int i = 0; i <= 100; i++) {
            System.out.println("whole numbers=" + i);
        }
    }

    public static void main(String[] args) {
        nat();
        System.out.println("     ");
        whole();
    }
}
